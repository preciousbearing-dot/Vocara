// Copies the web fonts out of node_modules into www/fonts and writes css/fonts.css.
// Runs in CI before the Android build. If the packages are missing it writes an
// empty stylesheet and the app falls back to system fonts.
import { copyFile, mkdir, readdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const out = join(root, 'www', 'fonts');
await mkdir(out, { recursive: true });

const wanted = [
  { pkg: 'plus-jakarta-sans', family: 'Plus Jakarta Sans', weights: [500, 600, 700, 800], style: 'normal' },
  { pkg: 'literata', family: 'Literata', weights: [400, 500], style: 'normal' },
];

let css = '/* generated by scripts/prepare-web.mjs */\n';
for (const f of wanted) {
  const dir = join(root, 'node_modules', '@fontsource', f.pkg, 'files');
  if (!existsSync(dir)) { console.warn(`missing ${f.pkg}, using system font`); continue; }
  const files = await readdir(dir);
  for (const w of f.weights) {
    const name = `${f.pkg}-latin-${w}-${f.style}.woff2`;
    if (!files.includes(name)) { console.warn(`missing ${name}`); continue; }
    await copyFile(join(dir, name), join(out, name));
    css += `@font-face{font-family:'${f.family}';font-style:${f.style};font-weight:${w};font-display:swap;src:url('../fonts/${name}') format('woff2');}\n`;
  }
}
await writeFile(join(root, 'www', 'css', 'fonts.css'), css);
console.log('fonts ready');
